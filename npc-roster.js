/** Три уровня памяти по числу встреч — простая, но осмысленная прогрессия. */
function getNpcLine(npcId, meetCount = 0) {
  const npc = NPC_ROSTER[npcId];
  if (!npc) return null;
  if (meetCount <= 0) return npc.memory.firstMeeting;
  if (meetCount < 5) return npc.memory.repeatMeeting;
  return npc.memory.trusted;
}

function getNpc(npcId) {
  return NPC_ROSTER[npcId] || null;
}

function npcsForStation(station) {
  return Object.values(NPC_ROSTER).filter((n) => n.station === station);
}

module.exports = { NPC_ROSTER, getNpcLine, getNpc, npcsForStation };
