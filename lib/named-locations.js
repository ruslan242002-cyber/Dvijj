/** Взвешенный выбор ресурса — фирменный ресурс темы получает удвоенный
* вес среди тех же 5 базовых ресурсов, остальные делят оставшееся
* поровну. Без темы (или без фирменного ресурса для неё) — обычный
* равномерный выбор, ничего не меняется. */
function pickResourceForTheme(resources, theme, rng) {
const favored = THEME_FAVORED_RESOURCE[theme];
if (!favored || !resources.includes(favored)) {
return resources[Math.floor(rng() * resources.length)];
}
const weights = resources.map((r) => (r === favored ? 2 : 1));
const total = weights.reduce((a, b) => a + b, 0);
let roll = rng() * total;
for (let i = 0; i < resources.length; i++) {
roll -= weights[i];
if (roll <= 0) return resources[i];
}
return resources[resources.length - 1];
}
