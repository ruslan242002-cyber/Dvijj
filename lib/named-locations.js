function pickEnemyNameForTheme(zoneNames, theme, rng) {
const themed = THEME_ENEMY_NAMES[theme];
if (!themed || !themed.length) return zoneNames[Math.floor(rng() * zoneNames.length)];
// Тематическое имя выпадает чаще, но не всегда — иногда обычный
// зональный враг тоже забредает на именное место, это нормально.
const pool = rng() < 0.65 ? themed : zoneNames;
return pool[Math.floor(rng() * pool.length)];
}
function locationsForZone(zone) {
return LOCATIONS_BY_ZONE[zone] || LOCATIONS_BY_ZONE.blue;
}
/**
* ПОЭТАПНОЕ ОТКРЫТИЕ ПЛАНЕТ — по разбору "растянуть путешествие": раньше
* locationsForZone() всегда отдавала все 4 места сразу, как только игрок
* попадал в зону. Теперь глубина ВНУТРИ зоны решает, какие 2 из 4 видны:
* первая половина пути по зоне — первые 2 места по порядку в массиве,
* вторая половина — оставшиеся 2. Границы зоны берутся из
* ZONE_DISTANCE_BANDS (engine/travel.js) — единый источник правды для
* того, где начинается и заканчивается каждая зона.
*/
const { ZONE_DISTANCE_BANDS } = require('../engine/travel.js');
function zoneDistanceSpan(zone) {
const idx = ZONE_DISTANCE_BANDS.findIndex((b) => b.zone === zone);
const band = ZONE_DISTANCE_BANDS[idx];
const nextBand = ZONE_DISTANCE_BANDS[idx + 1];
const start = band.minDistance;
// Для последней зоны (red) явного потолка нет по дизайну — топливо и
// риск сами ограничивают глубину, не эта функция. Берём тот же запас
// (12), что и у blue, только чтобы было от чего считать половину.
const end = nextBand ? nextBand.minDistance - 1 : start + 12;
return { start, end };
}
function locationsForZoneAtDistance(zone, distance) {
const all = locationsForZone(zone);
const { start, end } = zoneDistanceSpan(zone);
const span = end - start + 1;
const half = Math.ceil(all.length / 2);
const offsetInZone = Math.max(0, distance - start);
const isSecondHalf = offsetInZone >= Math.ceil(span / 2);
return isSecondHalf ? all.slice(half) : all.slice(0, half);
}
function findLocationById(id) {
for (const zone of Object.values(LOCATIONS_BY_ZONE)) {
const found = zone.find((loc) => loc.id === id);
if (found) return found;
}
return null;
}
