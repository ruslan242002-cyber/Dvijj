/**
 * Роллит, появится ли находка на этом тике, и если да — какая. Возвращает
 * null (ничего не выпало) либо объект { name, text, reward }.
 */
function rollMicroDiscovery(pool, rng = Math.random) {
  if (rng() >= MICRO_DISCOVERY_CHANCE) return null;
  return pool[Math.floor(rng() * pool.length)];
}

