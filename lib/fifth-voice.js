const FIRST_CONTACT_TEXT =
  '…между ударами сердца — что-то ещё. Не мысль. Не память. Голос, которого здесь быть не должно, ' +
  'произносит одно слово, и ты не уверен(а), что расслышал(а) верно: «Смотри».\n\n' +
  'Ты списываешь это на усталость. Но голос запомнил тебя первым.';

const VOICE_LINES = {
  level_8: 'Голос: «Ты растёшь. Хорошо. Расти дальше — я подожду».',
  level_15: 'Голос: «Половина пути. Ты ещё не спрашиваешь, откуда я. Спроси».',
  level_22: 'Голос: «Тракт помнит тех, кто его слушает. Я — то, чем он помнит».',
  level_30: 'Голос: «Скоро ты поймёшь, что я не советчик. Я — то, что осталось».',
  abyss_first_touch: 'Голос (тише обычного): «Ты коснулся(лась) того же, чем являюсь я. Теперь мы ближе».',
  vein_boss_first_kill: 'Голос: «Ты убил(а) то, что защищало руду для Тракта. Он это заметит».',
};

/** Триггеры — вызывать в соответствующих точках игры (левел-ап, первое
 * применение Бездны, первое убийство босса жилы). Возвращает текст
 * реплики или null, если для этого триггера ничего не звучит (либо
 * триггер не существует, либо уже звучал раньше). */
function maybeSpeak(player, triggerId) {
  if (!VOICE_LINES[triggerId]) return null;
  player.fifthVoiceHeard = player.fifthVoiceHeard || [];
  if (player.fifthVoiceHeard.includes(triggerId)) return null;

  const isFirstContactEver = player.fifthVoiceHeard.length === 0;
  player.fifthVoiceHeard.push(triggerId);

  const line = VOICE_LINES[triggerId];
  return isFirstContactEver ? `${FIRST_CONTACT_TEXT}\n\n${line}` : line;
}

function levelTriggerFor(level) {
  if (level === 8) return 'level_8';
  if (level === 15) return 'level_15';
  if (level === 22) return 'level_22';
  if (level === 30) return 'level_30';
  return null;
}

module.exports = { FIRST_CONTACT_TEXT, VOICE_LINES, maybeSpeak, levelTriggerFor };

