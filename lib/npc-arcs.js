/** Первая доступная СЕЙЧАС стадия для этого NPC, либо null если все
 * пройдены или их ещё нет вообще (arc не построена). */
function getAvailableStage(npcId, player) {
  const arc = NPC_ARCS[npcId];
  if (!arc) return null;
  return arc.stages.find((s) => s.condition(player)) || null;
}

function findStage(npcId, stageId) {
  const arc = NPC_ARCS[npcId];
  if (!arc) return null;
  return arc.stages.find((s) => s.id === stageId) || null;
}

function completeStage(player, npcId, stageId) {
  const stage = findStage(npcId, stageId);
  if (!stage) return;
  player.flags = player.flags || {};
  player.flags[stage.completionFlag] = true;
}

module.exports = { NPC_ARCS, getAvailableStage, findStage, completeStage };
