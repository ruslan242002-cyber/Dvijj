function checkQuestSiteEncounter(player, zone) {
  for (const [id, site] of Object.entries(QUEST_SITES)) {
    if (site.zone !== zone) continue;
    if (!player.flags?.[site.requiredFlag]) continue;
    if (player.flags?.[site.resolvedFlag]) continue;
    return { siteId: id, ...site };
  }
  return null;
}

