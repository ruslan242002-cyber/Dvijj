'use strict';

/**
 * ИДЕМПОТЕНТНОСТЬ ПО EVENT_ID — отдельная защита от lib/player-lock.js,
 * закрывает другой сценарий гонки:
 *
 * player-lock.js:  не даёт ДВУМ запросам одного игрока выполниться
 *                   ОДНОВРЕМЕННО (спам-клики, двойная отправка от VK
 *                   пока клиент ждёт ответа) — блокировка снимается сразу
 *                   после обработки, конфликт возможен только в узком
 *                   окне "запрос ещё не завершён".
 *
 * lib/idempotency.js: не даёт ОДНО И ТО ЖЕ событие VK обработать ДВАЖДЫ,
 *                   даже если между попытками прошли часы — VK Callback
 *                   API повторно доставляет событие, если не получил
 *                   'ok' вовремя (таймаут, холодный старт serverless,
 *                   временная ошибка сети), и это может случиться уже
 *                   после того, как первая попытка успешно завершилась и
 *                   лок давно снят. Без этой защиты повторная доставка
 *                   купленного лота/награды с босса/платежа спишет или
 *                   начислит дважды.
 *
 * Ключ — message.id из VK (монотонно растущий, уникальный в рамках
 * сообщества на все типы событий message_new) — не переизобретаем
 * собственный event_id, используем то, что VK и так гарантирует.
 */

const PROCESSED_TTL_SECONDS = 24 * 60 * 60; // сутки — дольше VK не станет ретраить одно и то же событие

function processedKey(eventId) {
  return `event:processed:${eventId}`;
}

/**
 * Атомарно: если событие ещё не обрабатывалось — помечает его
 * обработанным и возвращает true (можно продолжать). Если уже
 * обрабатывалось — возвращает false (это повтор, нужно тихо
 * подтвердить и ничего не делать повторно). SETNX сам по себе атомарен,
 * отдельный Lua-скрипт не нужен — здесь только одна операция, не
 * read-modify-write из нескольких шагов.
 *
 * Деградирует в сторону "разрешить" (true), если deps.redis недоступен —
 * лучше пропустить редкий дубль, чем полностью заблокировать бота при
 * сбое Redis (тот же принцип "диагностика не должна ронять игру", что и
 * в lib/economy-audit.js, только здесь ставки выше — поэтому это
 * единственное место, где деградация идёт в сторону "пропустить", а не
 * "заблокировать").
 */
async function markEventProcessedOnce(deps, eventId) {
  if (!eventId) return true; // нет id — не можем дедуплицировать, не блокируем на этом основании
  if (!deps.redis) return true;
  try {
    const result = await deps.redis.set(processedKey(eventId), '1', { nx: true, ex: PROCESSED_TTL_SECONDS });
    return result !== null; // Upstash: null означает "ключ уже существовал", SETNX не сработал
  } catch (err) {
    return true; // сбой Redis — пропускаем, не блокируем игрока из-за диагностики
  }
}

module.exports = { markEventProcessedOnce, PROCESSED_TTL_SECONDS };
