function getArcForFaction(faction) {
  return CURATOR_ARCS[faction] || null;
}

/** Следующий квест арки, который игрок ещё не завершил и может начать
 * (учитывает prerequisites через isQuestAvailable из quest-engine.js). */
function getNextAvailableQuest(player, arc) {
  if (!arc) return null;
  const completed = player.completedQuests || [];
  for (const quest of arc.quests) {
    if (completed.includes(quest.id)) continue;
    if (isQuestAvailable(player, quest)) return quest;
  }
  return null;
}

module.exports = { CURATOR_ARCS, getArcForFaction, getNextAvailableQuest };
