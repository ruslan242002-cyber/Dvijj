const STATION_EVENT_CHANCE = 0.2;

function getStationEvent(eventId) {
  return STATION_EVENTS[eventId] || null;
}

function rollStationEvent(districtEvents, rng = Math.random) {
  if (!districtEvents || districtEvents.length === 0) return null;
  if (rng() > STATION_EVENT_CHANCE) return null;
  const eventId = districtEvents[Math.floor(rng() * districtEvents.length)];
  return getStationEvent(eventId);
}

